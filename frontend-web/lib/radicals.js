/**
 * Mendapatkan informasi radikal lengkap (Nama, Arti, Bacaan) berdasarkan karakter radikal.
 */
export function getRadicalInfo(radicalChar) {
    if (!radicalChar) return null;
    const clean = String(radicalChar).trim();
    const info = RADICAL_DATA[clean];
    if (info) {
        return {
            char: clean,
            name: info.name,
            meaning: info.meaning,
            reading: info.reading
        };
    }
    return {
        char: clean,
        name: clean,
        meaning: 'Radikal Pembentuk',
        reading: ''
    };
}

